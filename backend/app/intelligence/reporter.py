def _assemble_markdown(
    experiment_name: str,
    sections: list[ReportSection],
    report_meta: dict[str, Any],
) -> str:
    """Combine all sections into a single Markdown document."""
    lines: list[str] = [
        f"# Experiment Report: {experiment_name}",
        "",
        f"**Generated:** {report_meta['generated_at'].strftime('%Y-%m-%d %H:%M UTC')}  ",
        f"**Recommendation:** {report_meta['recommendation']}  ",
        f"**Confidence:** {report_meta['confidence_level']}  ",
        f"**Key metric:** {report_meta['key_metric']}",
        "",
        "---",
        "",
    ]

    for section in sections:
        lines.append(f"## {section.section_number}. {section.title}")
        lines.append("")
        lines.append(section.content)
        lines.append("")

    return "\n".join(lines)


def _assemble_html(markdown_content: str) -> str:
    """Convert the assembled Markdown to a minimal HTML document.

    Handles: h1/h2/h3, bold, bullet lists, horizontal rules, paragraphs.
    Intentionally minimal — no external library dependency.
    """
    html = markdown_content

    # Escape HTML special chars that appear in table pipes etc. before conversion
    # Headers (order matters: h3 before h2 before h1)
    html = re.sub(r"^### (.+)$", r"<h3>\1</h3>", html, flags=re.MULTILINE)
    html = re.sub(r"^## (.+)$", r"<h2>\1</h2>", html, flags=re.MULTILINE)
    html = re.sub(r"^# (.+)$", r"<h1>\1</h1>", html, flags=re.MULTILINE)

    # Bold
    html = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", html)

    # Horizontal rule
    html = re.sub(r"^---$", "<hr/>", html, flags=re.MULTILINE)

    # Markdown tables → pass through as pre-formatted
    # (complex; leave as-is inside a <pre> block)
    lines = html.split("\n")
    out: list[str] = []
    in_list = False
    in_table = False

    for line in lines:
        stripped = line.strip()

        # Detect table rows
        if stripped.startswith("|") and stripped.endswith("|"):
            if not in_table:
                out.append("<table>")
                in_table = True
            # Skip separator rows (|---|---|)
            if re.match(r"^\|[-| ]+\|$", stripped):
                continue
            cells = [c.strip() for c in stripped.strip("|").split("|")]
            out.append(
                "<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>"
            )
            continue
        else:
            if in_table:
                out.append("</table>")
                in_table = False

        # Bullet lists
        if stripped.startswith("- ") or stripped.startswith("* "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{stripped[2:]}</li>")
            continue
        else:
            if in_list:
                out.append("</ul>")
                in_list = False

        # Already-converted HTML tags pass through
        if stripped.startswith("<") or not stripped:
            out.append(line)
        else:
            out.append(f"<p>{line}</p>")

    if in_list:
        out.append("</ul>")
    if in_table:
        out.append("</table>")

    body = "\n".join(out)
    return (
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head><meta charset=\"utf-8\">"
        "<title>Experiment Report</title></head>\n<body>\n"
        f"{body}\n</body>\n</html>"
    )


def _count_words(sections: list[ReportSection]) -> int:
    """Count words across sections 1–7 only (not the appendix)."""
    text = " ".join(
        s.content for s in sections if s.section_number < 8
    )
    return len(text.split())


# ---------------------------------------------------------------------------
# DB logging
# ---------------------------------------------------------------------------


async def _log_to_db(
    db: Any,
    *,
    experiment_id: Any,
    experiment_name: str,
    tool_output_json: str,
    input_tokens: int,
    output_tokens: int,
    duration_ms: int,
) -> None:
    """Write a row to ai_interactions. Fails silently so reporting is never blocked."""
    if db is None:
        return
    try:
        from app.models.experiment import AIInteraction, InteractionType

        cost = (
            input_tokens * _COST_PER_INPUT_TOKEN
            + output_tokens * _COST_PER_OUTPUT_TOKEN
        )
        record = AIInteraction(
            experiment_id=experiment_id,
            interaction_type=InteractionType.report,
            user_prompt=experiment_name,
            ai_response=tool_output_json,
            tokens_used=input_tokens + output_tokens,
            prompt_version=PROMPT_VERSION,
            input_tokens=input_tokens,
            output_tokens=output_tokens,
            estimated_cost_usd=cost,
            duration_ms=duration_ms,
        )
        db.add(record)
        await db.flush()
    except Exception as exc:
        logger.warning("Failed to log report interaction to DB: %s", exc)


# ---------------------------------------------------------------------------
# Core report generation function
# ---------------------------------------------------------------------------


async def generate_report(
    experiment_name: str,
    stats_result: FullAnalysisResult,
    ml_result: MLAnalysisSummary,
    daily_traffic: int | None = None,
    daily_revenue: float | None = None,
    format: Literal["markdown", "html"] = "markdown",
    db: Any = None,
    experiment_id: Any = None,
) -> StakeholderReport:
    """Generate a stakeholder report from experiment results.

    Calls Claude via tool_use to generate sections 1–7. Section 8 is always
    built programmatically. A grounding validator checks the recommendation
    and flags p-value leakage before the report is assembled.

    On Claude API failure, generates a complete programmatic fallback report
    (no AI, all sections from templates) and marks it clearly as a fallback.

    Args:
        experiment_name: Human-readable experiment name.
        stats_result: Statistical analysis output.
        ml_result: ML analysis summary (anomaly, novelty, HTE, segments).
        daily_traffic: Optional daily user count for context.
        daily_revenue: Optional daily revenue for business impact calculation.
        format: Preferred output format — both markdown_content and html_content
                are always generated regardless of this parameter.
        db: AsyncSession for logging. May be None in tests.
        experiment_id: UUID for DB logging. May be None.

    Returns:
        StakeholderReport with all 8 sections, full markdown, and HTML.
    """
    client = anthropic.AsyncAnthropic(api_key=settings.ANTHROPIC_API_KEY)
    user_message = _build_user_message(
        experiment_name, stats_result, ml_result, daily_traffic, daily_revenue
    )

    t0 = time.monotonic()
    try:
        response = await client.messages.create(
            model=CLAUDE_MODEL,
            max_tokens=2048,
            system=_SYSTEM_PROMPT,
            tools=[_TOOL_SCHEMA],
            tool_choice={"type": "tool", "name": "write_experiment_report"},
            messages=[{"role": "user", "content": user_message}],
            timeout=TIMEOUT_SECONDS,
        )
    except (anthropic.APITimeoutError, anthropic.APIError) as exc:
        logger.warning(
            "reporter: Claude API error for experiment=%r — generating fallback: %s",
            experiment_name,
            exc,
        )
        return build_fallback_report(
            experiment_name=experiment_name,
            stats_result=stats_result,
            ml_result=ml_result,
            daily_traffic=daily_traffic,
            daily_revenue=daily_revenue,
        )

    duration_ms = int((time.monotonic() - t0) * 1000)
    input_tokens: int = response.usage.input_tokens
    output_tokens: int = response.usage.output_tokens

    tool_block = next(
        (b for b in response.content if b.type == "tool_use"),
        None,
    )
    if tool_block is None:
        logger.warning(
            "reporter: no tool_use block returned for experiment=%r — generating fallback",
            experiment_name,
        )
        return build_fallback_report(
            experiment_name=experiment_name,
            stats_result=stats_result,
            ml_result=ml_result,
            daily_traffic=daily_traffic,
            daily_revenue=daily_revenue,
        )

    tool_output: dict[str, Any] = dict(tool_block.input)

    # Run grounding validator — fixes recommendation and logs issues
    tool_output = _validate_grounding(tool_output, stats_result, ml_result, daily_revenue)

    await _log_to_db(
        db,
        experiment_id=experiment_id,
        experiment_name=experiment_name,
        tool_output_json=json.dumps(tool_output),
        input_tokens=input_tokens,
        output_tokens=output_tokens,
        duration_ms=duration_ms,
    )

    # Build typed sections 1–7
    sections: list[ReportSection] = []
    for i in range(1, 8):
        key = f"section_{i}"
        content = tool_output.get(key, f"[Section {i} not generated]")
        sections.append(
            ReportSection(
                section_number=i,
                title=_SECTION_TITLES[i],
                content=content,
                is_ai_generated=True,
                data_sources=_section_data_sources(i),
            )
        )

    # Build section 8 — always programmatic
    sections.append(_build_section_8(stats_result, ml_result))

    recommendation: Literal["SHIP", "DO_NOT_SHIP", "EXTEND", "INVESTIGATE"] = (
        tool_output.get("recommendation", "INVESTIGATE")
    )
    confidence_level: Literal["High", "Medium", "Low"] = (
        tool_output.get("confidence_level", "Low")
    )

    now = datetime.now(timezone.utc)
    report_meta = {
        "generated_at": now,
        "recommendation": recommendation,
        "confidence_level": confidence_level,
        "key_metric": tool_output.get("key_metric", ""),
    }

    markdown_content = _assemble_markdown(experiment_name, sections, report_meta)
    html_content = _assemble_html(markdown_content)
    word_count = _count_words(sections)

    logger.info(
        "reporter: generated report experiment=%r recommendation=%s confidence=%s "
        "words=%d tokens_in=%d tokens_out=%d duration_ms=%d",
        experiment_name,
        recommendation,
        confidence_level,
        word_count,
        input_tokens,
        output_tokens,
        duration_ms,
    )

    return StakeholderReport(
        title=f"Experiment Report: {experiment_name}",
        generated_at=now,
        prompt_version=PROMPT_VERSION,
        sections=sections,
        markdown_content=markdown_content,
        html_content=html_content,
        key_metric=tool_output.get("key_metric", ""),
        recommendation=recommendation,
        confidence_level=confidence_level,
        confidence_reasoning=tool_output.get("confidence_reasoning", ""),
        word_count=word_count,
        ai_generated_sections=[_SECTION_TITLES[i] for i in range(1, 8)],
        programmatic_sections=[_SECTION_TITLES[8]],
    )


