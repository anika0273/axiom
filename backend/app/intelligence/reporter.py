"""Stakeholder report generator — Phase 3 intelligence layer.

Produces an 8-section executive-ready report from experiment results. Claude
generates sections 1–7 via tool_use; section 8 (Technical Appendix) is always
programmatic. A grounding validator runs after generation to catch recommendation
inconsistencies and flag p-value leakage into non-technical sections.

Exports:
    ReportSection        — one section of the report
    StakeholderReport    — full assembled report dataclass
    generate_report      — async: call Claude and assemble the report
    build_fallback_report — sync: template-based report, no Claude needed
"""

