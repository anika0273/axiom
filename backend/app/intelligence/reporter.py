# Programmatic fallback report
# ---------------------------------------------------------------------------


def build_fallback_report(
    experiment_name: str,
    stats_result: FullAnalysisResult,
    ml_result: MLAnalysisSummary,
    daily_traffic: int | None = None,
    daily_revenue: float | None = None,
) -> StakeholderReport:
    """Generate a complete report using only template logic — no Claude API.

    Called when the Claude API is unavailable. All 8 sections are programmatic.
    The report is clearly marked as a fallback in section 1.

    Args:
        experiment_name: Human-readable experiment name.
        stats_result: Statistical analysis output.
        ml_result: ML analysis summary.
        daily_traffic: Optional daily user count.
        daily_revenue: Optional daily revenue.

    Returns:
        StakeholderReport with all 8 sections, no AI content.
    """
    from app.intelligence.templates.fallback_report import build_fallback_sections

    sections_data = build_fallback_sections(
        experiment_name=experiment_name,
        stats=stats_result,
        ml=ml_result,
        daily_traffic=daily_traffic,
        daily_revenue=daily_revenue,
    )

    sections: list[ReportSection] = []
    for i in range(1, 8):
        sections.append(
            ReportSection(
                section_number=i,
                title=_SECTION_TITLES[i],
                content=sections_data[i],
                is_ai_generated=False,
                data_sources=_section_data_sources(i),
            )
        )
    sections.append(_build_section_8(stats_result, ml_result))

    recommendation = _derive_recommendation(stats_result, ml_result)
    confidence_level = _derive_confidence(stats_result, ml_result)

    if not stats_result.is_significant:
        key_metric = f"No significant effect (lift: {stats_result.lift_pct:+.1f}%)"
    elif not ml_result.can_trust_results:
        key_metric = "Results invalid — do not act"
    else:
        key_metric = f"{stats_result.lift_pct:+.1f}% lift (significant)"

    now = datetime.now(timezone.utc)
    report_meta = {
        "generated_at": now,
        "recommendation": recommendation,
        "confidence_level": confidence_level,
        "key_metric": key_metric,
    }

    markdown_content = _assemble_markdown(experiment_name, sections, report_meta)
    html_content = _assemble_html(markdown_content)
    word_count = _count_words(sections)

    return StakeholderReport(
        title=f"Experiment Report: {experiment_name}",
        generated_at=now,
        prompt_version=f"{PROMPT_VERSION}_fallback",
        sections=sections,
        markdown_content=markdown_content,
        html_content=html_content,
        key_metric=key_metric,
        recommendation=recommendation,
        confidence_level=confidence_level,
        confidence_reasoning="AI unavailable — report generated from templates.",
        word_count=word_count,
        ai_generated_sections=[],
        programmatic_sections=[_SECTION_TITLES[i] for i in range(1, 9)],
    )


def _derive_recommendation(
    stats: FullAnalysisResult,
    ml: MLAnalysisSummary,
) -> Literal["SHIP", "DO_NOT_SHIP", "EXTEND", "INVESTIGATE"]:
    """Deterministic recommendation from results — mirrors grounding validator logic."""
    if not ml.can_trust_results:
        return "INVESTIGATE"
    if ml.novelty_pattern in ("NOVELTY", "LEARNING"):
        return "EXTEND"
    if not stats.is_significant:
        return "DO_NOT_SHIP"
    if ml.overall_verdict == "NEEDS_REVIEW":
        return "SHIP"
    return "SHIP"


def _derive_confidence(
    stats: FullAnalysisResult,
    ml: MLAnalysisSummary,
) -> Literal["High", "Medium", "Low"]:
    """Deterministic confidence level from results."""
    if not ml.can_trust_results or not stats.is_significant:
        return "Low"
    if ml.novelty_pattern in ("NOVELTY", "LEARNING") or ml.overall_verdict == "NEEDS_REVIEW":
        return "Medium"
    return "High"
