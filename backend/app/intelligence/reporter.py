def _build_user_message(
    experiment_name: str,
    stats: FullAnalysisResult,
    ml: MLAnalysisSummary,
    daily_traffic: int | None,
    daily_revenue: float | None,
) -> str:
    """Construct the grounded user message sent to Claude.

    All numerical values are injected explicitly so Claude never needs to
    invent or estimate any figure.
    """
    lines: list[str] = [
        f"Experiment: {experiment_name}",
        "",
        "=== DATA SECTION (use these values exactly — do not invent other numbers) ===",
        "",
        "STATISTICAL RESULTS:",
        f"  is_significant: {stats.is_significant}",
        f"  lift_pct (relative lift, %): {stats.lift_pct:+.4f}",
        f"  lift_abs (absolute lift): {stats.lift_abs:+.6f}",
        f"  overall_recommendation: {stats.overall_recommendation}",
    ]

    if stats.warnings:
        lines.append(f"  stats_warnings: {'; '.join(stats.warnings)}")

    lines += [
        "",
        "ML VALIDITY:",
        f"  overall_verdict: {ml.overall_verdict}",
        f"  can_trust_results: {ml.can_trust_results}",
        f"  ml_recommendation: {ml.recommendation}",
    ]

    if ml.anomaly_validity:
        lines.append(f"  anomaly_validity: {ml.anomaly_validity}")
    if ml.novelty_pattern:
        lines.append(f"  novelty_pattern: {ml.novelty_pattern}")

    if ml.hte_top_modifier:
        modifier_clean = ml.hte_top_modifier.replace("_x_treat", "")
        lines.append(f"  hte_top_modifier: {modifier_clean}")
        if ml.hte_ate is not None:
            lines.append(f"  hte_ate: {ml.hte_ate:+.4f}")
        if ml.hte_business_recommendation:
            lines.append(f"  hte_recommendation: {ml.hte_business_recommendation}")

    if ml.responsive_segments is not None:
        lines.append(f"  responsive_segments: {ml.responsive_segments}")
    if ml.segment_recommendation:
        lines.append(f"  segment_recommendation: {ml.segment_recommendation}")

    if ml.key_insights:
        lines += ["", "KEY INSIGHTS FROM ML ENGINE:"]
        for insight in ml.key_insights:
            lines.append(f"  - {insight}")

    lines.append("")
    lines.append("CONTEXT:")
    if daily_traffic is not None:
        lines.append(f"  daily_traffic: {daily_traffic} users/day")
    if daily_revenue is not None:
        lines.append(f"  daily_revenue: ${daily_revenue:,.2f}")
    else:
        lines.append("  daily_revenue: not provided — do NOT invent revenue figures")

    lines += [
        "",
        "=== END DATA SECTION ===",
        "",
        "Write the experiment report following the structure in your instructions.",
        "Use the exact numerical values from the DATA SECTION above.",
        "Sections 1–7 only — section 8 is generated by code.",
    ]

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Section 8 — Technical Appendix (always programmatic)
# ---------------------------------------------------------------------------


def _build_section_8(
    stats: FullAnalysisResult,
    ml: MLAnalysisSummary,
) -> ReportSection:
    """Build the technical appendix from raw result values — no AI involved.

    This section is the only place where p-values, test statistics, and
    raw module outputs appear. It is always marked is_ai_generated=False.
    """
    lines: list[str] = [
        "### Statistical Results",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Statistically significant | {'Yes' if stats.is_significant else 'No'} |",
        f"| Relative lift | {stats.lift_pct:+.4f}% |",
        f"| Absolute lift | {stats.lift_abs:+.6f} |",
        f"| p-value | {stats.p_value:.6f} |",
        f"| Engine recommendation | {stats.overall_recommendation} |",
    ]

    if stats.warnings:
        lines += [
            "",
            "**Statistical warnings:**",
        ]
        for w in stats.warnings:
            lines.append(f"- {w}")

    lines += [
        "",
        "### ML Module Results",
        "",
        "| Module | Validity / Pattern |",
        "|---|---|",
    ]

    if ml.anomaly_validity:
        lines.append(f"| Anomaly detection | {ml.anomaly_validity} |")
    else:
        lines.append("| Anomaly detection | skipped |")

    if ml.novelty_pattern:
        lines.append(f"| Novelty detection | {ml.novelty_pattern} |")
    else:
        lines.append("| Novelty detection | skipped |")

    if ml.hte_top_modifier:
        modifier_clean = ml.hte_top_modifier.replace("_x_treat", "")
        ate_str = f"{ml.hte_ate:+.4f}" if ml.hte_ate is not None else "N/A"
        lines.append(f"| HTE top modifier | {modifier_clean} (ATE={ate_str}) |")
    else:
        lines.append("| HTE | skipped or no top modifier |")

    if ml.responsive_segments is not None:
        lines.append(f"| Responsive segments | {ml.responsive_segments} |")
    else:
        lines.append("| Segment analysis | skipped |")

    lines += [
        "",
        "### Overall ML Verdict",
        "",
        f"**Verdict:** {ml.overall_verdict}  ",
        f"**Can trust results:** {'Yes' if ml.can_trust_results else 'No'}  ",
        f"**ML recommendation:** {ml.recommendation}",
        "",
        "### Generation Metadata",
        "",
        f"| Field | Value |",
        "|---|---|",
        f"| Prompt version | {PROMPT_VERSION} |",
        f"| Model | {CLAUDE_MODEL} |",
    ]

    if ml.key_insights:
        lines += [
            "",
            "### ML Key Insights",
            "",
        ]
        for insight in ml.key_insights:
            lines.append(f"- {insight}")

    return ReportSection(
        section_number=8,
        title=_SECTION_TITLES[8],
        content="\n".join(lines),
        is_ai_generated=False,
        data_sources=[
            "stats_result.p_value",
            "stats_result.lift_pct",
            "stats_result.lift_abs",
            "stats_result.is_significant",
            "ml_result.overall_verdict",
            "ml_result.anomaly_validity",
            "ml_result.novelty_pattern",
        ],
    )


# ---------------------------------------------------------------------------
# Grounding validator
# ---------------------------------------------------------------------------


def _validate_grounding(
    tool_output: dict[str, Any],
    stats: FullAnalysisResult,
    ml: MLAnalysisSummary,
    daily_revenue: float | None,
) -> dict[str, Any]:
    """Validate and fix inconsistencies in Claude's tool output.

    Fixes recommendation mismatches in-place. Logs warnings for p-value
    leakage and business-impact errors but does not modify section text.

    Args:
        tool_output: Raw dict from Claude's write_experiment_report tool call.
        stats: Statistical results used for consistency checks.
        ml: ML results used for consistency checks.
        daily_revenue: If provided, validates business impact arithmetic.

    Returns:
        Possibly-modified tool_output dict.
    """
    rec: str = tool_output.get("recommendation", "")

    # Fix recommendation inconsistencies
    if rec == "SHIP" and not ml.can_trust_results:
        logger.warning(
            "grounding: SHIP recommended but can_trust_results=False — overriding to INVESTIGATE"
        )
        tool_output["recommendation"] = "INVESTIGATE"
        rec = "INVESTIGATE"

    if rec == "SHIP" and ml.novelty_pattern in ("NOVELTY", "LEARNING"):
        logger.warning(
            "grounding: SHIP recommended with novelty_pattern=%s — overriding to EXTEND",
            ml.novelty_pattern,
        )
        tool_output["recommendation"] = "EXTEND"
        rec = "EXTEND"

    if rec == "SHIP" and not stats.is_significant:
        logger.warning(
            "grounding: SHIP recommended but is_significant=False — overriding to EXTEND"
        )
        tool_output["recommendation"] = "EXTEND"
        rec = "EXTEND"

    # Check for p-value mentions in sections 1–7
    for i in range(1, 8):
        section_key = f"section_{i}"
        content = tool_output.get(section_key, "")
        if _PVALUE_PATTERN.search(content):
            logger.warning(
                "grounding: statistical jargon (p-value/z-score) detected in %s", section_key
            )

    # Validate business impact arithmetic when daily_revenue is available
    if daily_revenue is not None and stats.is_significant:
        expected_monthly = abs(stats.lift_pct / 100.0) * daily_revenue * 30
        section_2 = tool_output.get("section_2", "")
        # Extract any dollar figures from section 2
        dollar_matches = re.findall(r"\$[\d,]+(?:\.\d+)?", section_2)
        for match in dollar_matches:
            val = float(match.replace("$", "").replace(",", ""))
            # Flag if the stated monthly figure is off by more than 50%
            if val > 1000 and abs(val - expected_monthly) / max(expected_monthly, 1) > 0.5:
                logger.warning(
                    "grounding: business impact $%.0f in section_2 differs from "
                    "expected $%.0f by >50%%",
                    val,
                    expected_monthly,
                )
                break

    # Validate key_metric is non-empty
    if not tool_output.get("key_metric", "").strip():
        if stats.is_significant:
            tool_output["key_metric"] = f"{stats.lift_pct:+.1f}% lift (significant)"
        else:
            tool_output["key_metric"] = (
                f"No significant effect (lift: {stats.lift_pct:+.1f}%)"
            )
        logger.warning("grounding: key_metric was empty — substituted from stats data")

    return tool_output


