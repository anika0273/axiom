@dataclass
class ReportSection:
    """One section of the stakeholder report.

    Attributes:
        section_number: 1–8.
        title: Human-readable section title.
        content: Markdown-formatted section body.
        is_ai_generated: True for sections 1–7; False for section 8.
        data_sources: Fields from stats/ML results used to build this section.
    """

    section_number: int
    title: str
    content: str
    is_ai_generated: bool
    data_sources: list[str]


@dataclass
class StakeholderReport:
    """Fully assembled stakeholder report.

    Attributes:
        title: Report title derived from experiment name.
        generated_at: UTC timestamp of generation.
        prompt_version: Prompt constant version used (e.g. "reporter_v1").
        sections: All 8 report sections in order.
        markdown_content: Full report as a single Markdown string.
        html_content: Full report as a minimal HTML document.
        key_metric: The single number an executive will remember.
        recommendation: SHIP / DO_NOT_SHIP / EXTEND / INVESTIGATE.
        confidence_level: High / Medium / Low.
        confidence_reasoning: One-sentence explanation of confidence level.
        word_count: Word count of sections 1–7 only (not the appendix).
        ai_generated_sections: Section titles generated by Claude.
        programmatic_sections: Section titles built by code.
    """

    title: str
    generated_at: datetime
    prompt_version: str
    sections: list[ReportSection]
    markdown_content: str
    html_content: str
    key_metric: str
    recommendation: Literal["SHIP", "DO_NOT_SHIP", "EXTEND", "INVESTIGATE"]
    confidence_level: Literal["High", "Medium", "Low"]
    confidence_reasoning: str
    word_count: int
    ai_generated_sections: list[str]
    programmatic_sections: list[str]


